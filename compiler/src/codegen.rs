use crate::ast::*;
use crate::errors::CompileError;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

pub struct CodeGen;

impl CodeGen {
    pub fn emit_rust(_program: &Program, source: &str) -> String {
        let escaped_source = source.replace('\\', "\\\\").replace('"', "\\\"");
        format!(
            r#"// Auto-generated by Blueprint Compiler
fn main() {{
    let src = "{escaped_source}";
    let mut interpreter = blueprint_compiler::Interpreter::new();
    let tokens = match blueprint_compiler::tokenize(src) {{
        Ok(t) => t,
        Err(e) => {{
            eprintln!("{{}}", e);
            std::process::exit(1);
        }}
    }};
    let prog = match blueprint_compiler::parse_program(src, tokens) {{
        Ok(p) => p,
        Err(e) => {{
            eprintln!("{{}}", e);
            std::process::exit(1);
        }}
    }};
    if let Err(e) = blueprint_compiler::analyze(src, &prog) {{
        eprintln!("{{}}", e);
        std::process::exit(1);
    }}
    if let Err(e) = interpreter.load_program(src, &prog) {{
        eprintln!("{{}}", e);
        std::process::exit(1);
    }}
    if let Err(e) = interpreter.run_main() {{
        eprintln!("{{}}", e);
        std::process::exit(1);
    }}
    for line in interpreter.runtime.output {{
        println!("{{}}", line);
    }}
}}
"#
        )
    }

    pub fn compile_to_executable(
        program: &Program,
        source: &str,
        output_exe: &Path,
    ) -> Result<PathBuf, CompileError> {
        let temp_dir = std::env::temp_dir().join(format!("bl_build_{}", std::process::id()));
        let _ = fs::create_dir_all(&temp_dir);

        let cargo_toml = r#"[package]
name = "blueprint_app"
version = "0.1.0"
edition = "2021"

[dependencies]
blueprint_compiler = { path = "REPLACE_COMPILER_PATH" }
"#;

        let manifest_dir = Path::new(env!("CARGO_MANIFEST_DIR"));
        let compiler_path_str = manifest_dir.to_str().unwrap().replace('\\', "/");
        let cargo_toml = cargo_toml.replace("REPLACE_COMPILER_PATH", &compiler_path_str);

        let src_dir = temp_dir.join("src");
        let _ = fs::create_dir_all(&src_dir);

        let rust_code = Self::emit_rust(program, source);
        let _ = fs::write(temp_dir.join("Cargo.toml"), cargo_toml);
        let _ = fs::write(src_dir.join("main.rs"), rust_code);

        // Run cargo build in temp_dir
        let status = Command::new("cargo")
            .arg("build")
            .arg("--release")
            .current_dir(&temp_dir)
            .status()
            .map_err(|e| CompileError::new(&format!("Failed to invoke cargo: {}", e)))?;

        if !status.success() {
            return Err(CompileError::new(
                "Native executable compilation failed during cargo build",
            ));
        }

        let built_exe = temp_dir
            .join("target")
            .join("release")
            .join("blueprint_app.exe");
        if !built_exe.exists() {
            return Err(CompileError::new(
                "Executable binary was not produced in target/release",
            ));
        }

        if let Some(parent) = output_exe.parent() {
            let _ = fs::create_dir_all(parent);
        }
        fs::copy(&built_exe, output_exe).map_err(|e| {
            CompileError::new(&format!(
                "Failed to write output executable to '{}': {}",
                output_exe.display(),
                e
            ))
        })?;

        // Clean up temp_dir
        let _ = fs::remove_dir_all(&temp_dir);

        Ok(output_exe.to_path_buf())
    }
}

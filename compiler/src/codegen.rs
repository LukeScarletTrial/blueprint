use crate::ast::*;
use crate::errors::CompileError;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

pub struct CodeGen;

impl CodeGen {
    /// Generates standalone, self-contained C source code directly from the Blueprint AST.
    /// This produces true native machine code without embedding any interpreter or runtime VM.
    pub fn emit_c(program: &Program) -> String {
        let mut out = String::new();

        out.push_str("/* Standalone Native Executable generated by Blueprint Compiler */\n");
        out.push_str("#include <stdio.h>\n");
        out.push_str("#include <stdlib.h>\n");
        out.push_str("#include <string.h>\n");
        out.push_str("#include <stdbool.h>\n");
        out.push_str("#include <stdint.h>\n\n");

        // Runtime helpers: string concatenation and output
        out.push_str("static char* bl_concat(const char* s1, const char* s2) {\n");
        out.push_str("    size_t len1 = strlen(s1);\n");
        out.push_str("    size_t len2 = strlen(s2);\n");
        out.push_str("    char* res = (char*)malloc(len1 + len2 + 1);\n");
        out.push_str("    memcpy(res, s1, len1);\n");
        out.push_str("    memcpy(res + len1, s2, len2 + 1);\n");
        out.push_str("    return res;\n");
        out.push_str("}\n\n");

        out.push_str("static char* bl_int_to_str(int64_t val) {\n");
        out.push_str("    char* buf = (char*)malloc(32);\n");
        out.push_str("    snprintf(buf, 32, \"%lld\", (long long)val);\n");
        out.push_str("    return buf;\n");
        out.push_str("}\n\n");

        out.push_str("static void bl_output_str(const char* s) {\n");
        out.push_str("    printf(\"%s\\n\", s);\n");
        out.push_str("}\n\n");

        out.push_str("static void bl_output_int(int64_t n) {\n");
        out.push_str("    printf(\"%lld\\n\", (long long)n);\n");
        out.push_str("}\n\n");

        // 1. Forward declare struct types
        for item in &program.items {
            if let Item::Struct(st) = item {
                out.push_str(&format!("typedef struct {} {};\n", st.name, st.name));
            }
        }
        out.push('\n');

        // 2. Define struct bodies
        for item in &program.items {
            if let Item::Struct(st) = item {
                out.push_str(&format!("struct {} {{\n", st.name));
                for f in &st.fields {
                    let c_type = Self::c_type(&f.ty);
                    out.push_str(&format!("    {} {};\n", c_type, f.name));
                }
                out.push_str("};\n\n");
            }
        }

        // 3. Forward declare function signatures
        for item in &program.items {
            if let Item::Func(func) = item {
                let ret_ty = func.return_ty.as_ref().map(Self::c_type).unwrap_or_else(|| "void".to_string());
                let params = Self::c_params(&func.params);
                out.push_str(&format!("{} {}({});\n", ret_ty, func.name, params));
            }
        }
        out.push('\n');

        // 4. Implement functions
        for item in &program.items {
            if let Item::Func(func) = item {
                let ret_ty = func.return_ty.as_ref().map(Self::c_type).unwrap_or_else(|| "void".to_string());
                let params = Self::c_params(&func.params);
                out.push_str(&format!("{} {}({}) {{\n", ret_ty, func.name, params));
                for stmt in &func.body {
                    Self::emit_stmt(&mut out, stmt, 1);
                }
                out.push_str("}\n\n");
            }
        }

        // 5. Entry point main() calling Blueprint Main()
        out.push_str("int main(int argc, char** argv) {\n");
        out.push_str("    (void)argc;\n");
        out.push_str("    (void)argv;\n");
        out.push_str("    Main();\n");
        out.push_str("    return 0;\n");
        out.push_str("}\n");

        out
    }

    fn c_type(ty: &Type) -> String {
        match ty {
            Type::Int => "int64_t".to_string(),
            Type::Bool => "bool".to_string(),
            Type::String => "const char*".to_string(),
            Type::Void => "void".to_string(),
            Type::Custom(name) => name.clone(),
        }
    }

    fn c_params(params: &[Param]) -> String {
        if params.is_empty() {
            return "void".to_string();
        }
        params
            .iter()
            .map(|p| {
                let ty = p.ty.as_ref().map(Self::c_type).unwrap_or_else(|| "const char*".to_string());
                format!("{} {}", ty, p.name)
            })
            .collect::<Vec<_>>()
            .join(", ")
    }

    fn emit_stmt(out: &mut String, stmt: &Stmt, indent_level: usize) {
        let ind = "    ".repeat(indent_level);
        match stmt {
            Stmt::VarDef(v) => {
                let expr_code = Self::emit_expr(&v.expr.expr);
                let ty_str = if let Some(ref ty) = v.explicit_ty {
                    Self::c_type(ty)
                } else {
                    // infer basic type or fallback to auto/pointer
                    "auto".to_string()
                };
                out.push_str(&format!("{}{} {} = {};\n", ind, ty_str, v.name, expr_code));
            }
            Stmt::Return(expr_opt, _) => {
                if let Some(e) = expr_opt {
                    out.push_str(&format!("{}return {};\n", ind, Self::emit_expr(&e.expr)));
                } else {
                    out.push_str(&format!("{}return;\n", ind));
                }
            }
            Stmt::If(if_stmt) => {
                let cond = Self::emit_expr(&if_stmt.condition.expr);
                out.push_str(&format!("{}if ({}) {{\n", ind, cond));
                for s in &if_stmt.then_branch {
                    Self::emit_stmt(out, s, indent_level + 1);
                }
                if let Some(ref else_branch) = if_stmt.else_branch {
                    out.push_str(&format!("{}}} else {{\n", ind));
                    for s in else_branch {
                        Self::emit_stmt(out, s, indent_level + 1);
                    }
                }
                out.push_str(&format!("{}}}\n", ind));
            }
            Stmt::Expr(e) => {
                let code = Self::emit_expr(&e.expr);
                out.push_str(&format!("{}{};\n", ind, code));
            }
        }
    }

    fn emit_expr(expr: &Expr) -> String {
        match expr {
            Expr::Int(n) => format!("{}LL", n),
            Expr::Bool(b) => if *b { "true".to_string() } else { "false".to_string() },
            Expr::String(s) => {
                let escaped = s.replace('\\', "\\\\").replace('"', "\\\"").replace('\n', "\\n");
                format!("\"{}\"", escaped)
            }
            Expr::Ident(name) => name.clone(),
            Expr::BinaryOp(left, op, right) => {
                let l = Self::emit_expr(&left.expr);
                let r = Self::emit_expr(&right.expr);
                match op {
                    BinOp::Add => {
                        // Check if string concatenation
                        format!("bl_concat({}, {})", l, r)
                    }
                    BinOp::Sub => format!("({} - {})", l, r),
                    BinOp::Mul => format!("({} * {})", l, r),
                    BinOp::Div => format!("({} / {})", l, r),
                    BinOp::Gt => format!("({} > {})", l, r),
                    BinOp::Lt => format!("({} < {})", l, r),
                    BinOp::Gte => format!("({} >= {})", l, r),
                    BinOp::Lte => format!("({} <= {})", l, r),
                    BinOp::EqEq => format!("({} == {})", l, r),
                    BinOp::Neq => format!("({} != {})", l, r),
                    BinOp::And => format!("({} && {})", l, r),
                    BinOp::Or => format!("({} || {})", l, r),
                }
            }
            Expr::UnaryOp(op, operand) => {
                let inner = Self::emit_expr(&operand.expr);
                match op {
                    UnOp::Neg => format!("(-{})", inner),
                    UnOp::Not => format!("(!{})", inner),
                }
            }
            Expr::Call(name, args) => {
                if name == "output" {
                    if let Some(first_arg) = args.first() {
                        let arg_code = Self::emit_expr(&first_arg.expr);
                        return format!("bl_output_str({})", arg_code);
                    }
                    return "bl_output_str(\"\")".to_string();
                }
                let rendered_args = args.iter().map(|a| Self::emit_expr(&a.expr)).collect::<Vec<_>>().join(", ");
                format!("{}({})", name, rendered_args)
            }
            Expr::FieldAccess(target, field) => {
                let t = Self::emit_expr(&target.expr);
                format!("{}.{}", t, field)
            }
            Expr::StructInit(struct_name, fields) => {
                let rendered_fields = fields
                    .iter()
                    .map(|(fname, val)| {
                        if fname.starts_with('_') {
                            Self::emit_expr(&val.expr)
                        } else {
                            format!(".{} = {}", fname, Self::emit_expr(&val.expr))
                        }
                    })
                    .collect::<Vec<_>>()
                    .join(", ");
                format!("({}){{ {} }}", struct_name, rendered_fields)
            }
            Expr::MethodCall(target, method, args) => {
                let t = Self::emit_expr(&target.expr);
                let rendered_args = args.iter().map(|a| Self::emit_expr(&a.expr)).collect::<Vec<_>>().join(", ");
                format!("{}_{}({}, {})", t, method, t, rendered_args)
            }
        }
    }

    /// Compiles directly to a standalone native binary using the system C compiler (gcc/clang).
    /// Does NOT invoke Cargo, does NOT embed the Blueprint interpreter.
    pub fn compile_to_executable(
        program: &Program,
        _source: &str,
        output_exe: &Path,
    ) -> Result<PathBuf, CompileError> {
        let temp_dir = std::env::temp_dir().join(format!("bl_build_{}", std::process::id()));
        let _ = fs::create_dir_all(&temp_dir);

        let c_source = Self::emit_c(program);
        let c_file = temp_dir.join("app.c");
        fs::write(&c_file, c_source).map_err(|e| {
            CompileError::new(&format!("Failed to write generated C file: {}", e))
        })?;

        if let Some(parent) = output_exe.parent() {
            let _ = fs::create_dir_all(parent);
        }

        // Prefer gcc or clang installed on system
        let status = Command::new("gcc")
            .arg("-O2")
            .arg("-std=c11")
            .arg("-o")
            .arg(output_exe)
            .arg(&c_file)
            .status()
            .map_err(|e| {
                CompileError::new(&format!(
                    "Failed to invoke native compiler 'gcc'. Make sure GCC/Clang is installed: {}",
                    e
                ))
            })?;

        let _ = fs::remove_dir_all(&temp_dir);

        if !status.success() {
            return Err(CompileError::new("Native compiler (gcc) reported build errors"));
        }

        if !output_exe.exists() {
            return Err(CompileError::new("Executable binary was not produced"));
        }

        Ok(output_exe.to_path_buf())
    }
}

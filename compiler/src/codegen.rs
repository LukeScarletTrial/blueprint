use crate::ast::*;
use crate::errors::CompileError;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

pub struct CodeGen;

impl CodeGen {
    /// Generates standalone, self-contained C source code directly from the Blueprint AST.
    /// This produces true native machine code without embedding any interpreter or runtime VM.
    pub fn emit_c(program: &Program) -> String {
        let mut out = String::new();

        out.push_str("/* Standalone Native Executable generated by Blueprint Compiler */\n");
        out.push_str("#include <stdio.h>\n");
        out.push_str("#include <stdlib.h>\n");
        out.push_str("#include <string.h>\n");
        out.push_str("#include <stdbool.h>\n");
        out.push_str("#include <stdint.h>\n");
        out.push_str("#include <math.h>\n\n");

        out.push_str("#ifdef _WIN32\n");
        out.push_str("#define WIN32_LEAN_AND_MEAN\n");
        out.push_str("#include <windows.h>\n");
        out.push_str("#endif\n\n");

        // Phase 3: C FFI — emit user-specified includes
        for inc in &program.c_includes {
            if inc.header.starts_with('<') || inc.header.starts_with('"') {
                out.push_str(&format!("#include {}\n", inc.header));
            } else {
                out.push_str(&format!("#include <{}>\n", inc.header));
            }
        }
        if !program.c_includes.is_empty() {
            out.push('\n');
        }

        // Phase 3: C FFI — emit extern function declarations
        if !program.c_externs.is_empty() {
            out.push_str("/* C FFI extern declarations */\n");
            for ext in &program.c_externs {
                out.push_str(&format!("extern {};\n", ext.signature));
            }
            out.push('\n');
        }

        // ARC (Automatic Reference Counting) Memory Model
        out.push_str("/* ========================================================================= */\n");
        out.push_str("/* ARC (Automatic Reference Counting) Memory Model                           */\n");
        out.push_str("/* ========================================================================= */\n\n");
        out.push_str("typedef struct {\n");
        out.push_str("    int32_t ref_count;\n");
        out.push_str("    size_t size;\n");
        out.push_str("} bl_arc_header_t;\n\n");

        out.push_str("static void* bl_arc_alloc(size_t payload_size) {\n");
        out.push_str("    bl_arc_header_t* header = (bl_arc_header_t*)malloc(sizeof(bl_arc_header_t) + payload_size);\n");
        out.push_str("    if (!header) { fprintf(stderr, \"Fatal: Out of memory\\n\"); exit(1); }\n");
        out.push_str("    header->ref_count = 1;\n");
        out.push_str("    header->size = payload_size;\n");
        out.push_str("    return (void*)(header + 1);\n");
        out.push_str("}\n\n");

        out.push_str("static void* bl_arc_retain(void* ptr) {\n");
        out.push_str("    if (!ptr) return NULL;\n");
        out.push_str("    bl_arc_header_t* header = ((bl_arc_header_t*)ptr) - 1;\n");
        out.push_str("    if (header->ref_count > 0) { header->ref_count++; }\n");
        out.push_str("    return ptr;\n");
        out.push_str("}\n\n");

        out.push_str("static void bl_arc_release(void* ptr) {\n");
        out.push_str("    if (!ptr) return;\n");
        out.push_str("    bl_arc_header_t* header = ((bl_arc_header_t*)ptr) - 1;\n");
        out.push_str("    if (header->ref_count > 0) {\n");
        out.push_str("        header->ref_count--;\n");
        out.push_str("        if (header->ref_count == 0) {\n");
        out.push_str("            free(header);\n");
        out.push_str("        }\n");
        out.push_str("    }\n");
        out.push_str("}\n\n");

        out.push_str("static char* bl_arc_str(const char* s) {\n");
        out.push_str("    if (!s) return NULL;\n");
        out.push_str("    size_t len = strlen(s);\n");
        out.push_str("    char* copy = (char*)bl_arc_alloc(len + 1);\n");
        out.push_str("    memcpy(copy, s, len + 1);\n");
        out.push_str("    return copy;\n");
        out.push_str("}\n\n");

        out.push_str("static char* bl_int_to_str(int64_t val) {\n");
        out.push_str("    char buf[64];\n");
        out.push_str("    snprintf(buf, sizeof(buf), \"%lld\", (long long)val);\n");
        out.push_str("    return bl_arc_str(buf);\n");
        out.push_str("}\n\n");

        out.push_str("static char* bl_float_to_str(double val) {\n");
        out.push_str("    char buf[64];\n");
        out.push_str("    snprintf(buf, sizeof(buf), \"%g\", val);\n");
        out.push_str("    return bl_arc_str(buf);\n");
        out.push_str("}\n\n");

        out.push_str("static char* bl_bool_to_str(bool val) {\n");
        out.push_str("    return bl_arc_str(val ? \"true\" : \"false\");\n");
        out.push_str("}\n\n");

        out.push_str("static const char* bl_pass_str(const char* s) { return s; }\n\n");

        out.push_str("#define bl_to_str(x) _Generic((x), \\\n");
        out.push_str("    int: bl_int_to_str, \\\n");
        out.push_str("    long: bl_int_to_str, \\\n");
        out.push_str("    long long: bl_int_to_str, \\\n");
        out.push_str("    float: bl_float_to_str, \\\n");
        out.push_str("    double: bl_float_to_str, \\\n");
        out.push_str("    bool: bl_bool_to_str, \\\n");
        out.push_str("    default: bl_pass_str \\\n");
        out.push_str(")(x)\n\n");

        out.push_str("static char* bl_concat(const char* s1, const char* s2) {\n");
        out.push_str("    if (!s1) s1 = \"\";\n");
        out.push_str("    if (!s2) s2 = \"\";\n");
        out.push_str("    size_t len1 = strlen(s1);\n");
        out.push_str("    size_t len2 = strlen(s2);\n");
        out.push_str("    char* res = (char*)bl_arc_alloc(len1 + len2 + 1);\n");
        out.push_str("    memcpy(res, s1, len1);\n");
        out.push_str("    memcpy(res + len1, s2, len2 + 1);\n");
        out.push_str("    return res;\n");
        out.push_str("}\n\n");

        // Standard library runtime helpers: IO and Math
        out.push_str("/* ========================================================================= */\n");
        out.push_str("/* Standard Library Functions                                               */\n");
        out.push_str("/* ========================================================================= */\n\n");
        out.push_str("static void bl_output_str(const char* s) {\n");
        out.push_str("    printf(\"%s\\n\", s ? s : \"\");\n");
        out.push_str("}\n\n");

        out.push_str("static void bl_output_int(int64_t n) {\n");
        out.push_str("    printf(\"%lld\\n\", (long long)n);\n");
        out.push_str("}\n\n");

        out.push_str("static void bl_output_float(double f) {\n");
        out.push_str("    printf(\"%g\\n\", f);\n");
        out.push_str("}\n\n");

        out.push_str("static char* bl_input(const char* prompt) {\n");
        out.push_str("    if (prompt && *prompt) {\n");
        out.push_str("        printf(\"%s\", prompt);\n");
        out.push_str("        fflush(stdout);\n");
        out.push_str("    }\n");
        out.push_str("    char buf[1024];\n");
        out.push_str("    if (fgets(buf, sizeof(buf), stdin)) {\n");
        out.push_str("        size_t len = strlen(buf);\n");
        out.push_str("        while (len > 0 && (buf[len - 1] == '\\n' || buf[len - 1] == '\\r')) {\n");
        out.push_str("            buf[len - 1] = '\\0';\n");
        out.push_str("            len--;\n");
        out.push_str("        }\n");
        out.push_str("        return bl_arc_str(buf);\n");
        out.push_str("    }\n");
        out.push_str("    return bl_arc_str(\"\");\n");
        out.push_str("}\n\n");

        out.push_str("static int64_t bl_str_len(const char* s) {\n");
        out.push_str("    return s ? (int64_t)strlen(s) : 0;\n");
        out.push_str("}\n\n");

        out.push_str("static int64_t bl_math_abs(int64_t n) {\n");
        out.push_str("    return n < 0 ? -n : n;\n");
        out.push_str("}\n\n");

        out.push_str("static int64_t bl_math_pow(int64_t base, int64_t exp) {\n");
        out.push_str("    if (exp <= 0) return 1;\n");
        out.push_str("    int64_t res = 1;\n");
        out.push_str("    for (int64_t i = 0; i < exp; ++i) { res *= base; }\n");
        out.push_str("    return res;\n");
        out.push_str("}\n\n");

        out.push_str("static int64_t bl_math_min(int64_t a, int64_t b) {\n");
        out.push_str("    return a < b ? a : b;\n");
        out.push_str("}\n\n");

        out.push_str("static int64_t bl_math_max(int64_t a, int64_t b) {\n");
        out.push_str("    return a > b ? a : b;\n");
        out.push_str("}\n\n");

        // =====================================================================
        // Phase 4: Extended Standard Library — File I/O, Path, Env, Process, Time
        // =====================================================================
        out.push_str("/* ========================================================================= */\n");
        out.push_str("/* Extended Standard Library (Phase 4)                                     */\n");
        out.push_str("/* ========================================================================= */\n\n");
        out.push_str("#include <time.h>\n\n");
        // Platform includes for sleep
        out.push_str("#ifdef _WIN32\n");
        out.push_str("#include <windows.h>\n");
        out.push_str("#else\n");
        out.push_str("#include <unistd.h>\n");
        out.push_str("#endif\n\n");

        // file_read(path) -> string
        out.push_str("static const char* bl_file_read(const char* path) {\n");
        out.push_str("    if (!path) return bl_arc_str(\"\");\n");
        out.push_str("    FILE* f = fopen(path, \"rb\");\n");
        out.push_str("    if (!f) return bl_arc_str(\"\");\n");
        out.push_str("    fseek(f, 0, SEEK_END);\n");
        out.push_str("    long sz = ftell(f);\n");
        out.push_str("    fseek(f, 0, SEEK_SET);\n");
        out.push_str("    if (sz <= 0) { fclose(f); return bl_arc_str(\"\"); }\n");
        out.push_str("    char* buf = (char*)bl_arc_alloc((size_t)sz + 1);\n");
        out.push_str("    size_t read_n = fread(buf, 1, (size_t)sz, f);\n");
        out.push_str("    buf[read_n] = '\\0';\n");
        out.push_str("    fclose(f);\n");
        out.push_str("    return buf;\n");
        out.push_str("}\n\n");

        // file_write(path, data) -> bool
        out.push_str("static bool bl_file_write(const char* path, const char* data) {\n");
        out.push_str("    if (!path || !data) return false;\n");
        out.push_str("    FILE* f = fopen(path, \"wb\");\n");
        out.push_str("    if (!f) return false;\n");
        out.push_str("    fputs(data, f);\n");
        out.push_str("    fclose(f);\n");
        out.push_str("    return true;\n");
        out.push_str("}\n\n");

        // file_exists(path) -> bool
        out.push_str("static bool bl_file_exists(const char* path) {\n");
        out.push_str("    if (!path) return false;\n");
        out.push_str("    FILE* f = fopen(path, \"rb\");\n");
        out.push_str("    if (f) { fclose(f); return true; }\n");
        out.push_str("    return false;\n");
        out.push_str("}\n\n");

        // path_join(a, b) -> string
        out.push_str("static const char* bl_path_join(const char* a, const char* b) {\n");
        out.push_str("    if (!a) a = \"\";\n");
        out.push_str("    if (!b) b = \"\";\n");
        out.push_str("    size_t la = strlen(a), lb = strlen(b);\n");
        out.push_str("    char* res = (char*)bl_arc_alloc(la + lb + 2);\n");
        out.push_str("    memcpy(res, a, la);\n");
        out.push_str("    if (la > 0 && a[la-1] != '/' && a[la-1] != '\\\\') res[la++] = '/';\n");
        out.push_str("    memcpy(res + la, b, lb + 1);\n");
        out.push_str("    return res;\n");
        out.push_str("}\n\n");

        // path_ext(p) -> string  (extension without dot)
        out.push_str("static const char* bl_path_ext(const char* p) {\n");
        out.push_str("    if (!p) return bl_arc_str(\"\");\n");
        out.push_str("    const char* dot = strrchr(p, '.');\n");
        out.push_str("    const char* slash = strrchr(p, '/');\n");
        out.push_str("    const char* bslash = strrchr(p, '\\\\');\n");
        out.push_str("    const char* sep = slash > bslash ? slash : bslash;\n");
        out.push_str("    if (!dot || (sep && dot < sep)) return bl_arc_str(\"\");\n");
        out.push_str("    return bl_arc_str(dot + 1);\n");
        out.push_str("}\n\n");

        // path_filename(p) -> string  (basename with extension)
        out.push_str("static const char* bl_path_filename(const char* p) {\n");
        out.push_str("    if (!p) return bl_arc_str(\"\");\n");
        out.push_str("    const char* slash = strrchr(p, '/');\n");
        out.push_str("    const char* bslash = strrchr(p, '\\\\');\n");
        out.push_str("    const char* sep = slash > bslash ? slash : bslash;\n");
        out.push_str("    return bl_arc_str(sep ? sep + 1 : p);\n");
        out.push_str("}\n\n");

        // env_get(key) -> string
        out.push_str("static const char* bl_env_get(const char* key) {\n");
        out.push_str("    if (!key) return bl_arc_str(\"\");\n");
        out.push_str("    const char* val = getenv(key);\n");
        out.push_str("    return bl_arc_str(val ? val : \"\");\n");
        out.push_str("}\n\n");

        // env_set(key, val) -> bool
        out.push_str("static bool bl_env_set(const char* key, const char* val) {\n");
        out.push_str("    if (!key) return false;\n");
        out.push_str("#ifdef _WIN32\n");
        out.push_str("    return SetEnvironmentVariableA(key, val) != 0;\n");
        out.push_str("#else\n");
        out.push_str("    return setenv(key, val ? val : \"\", 1) == 0;\n");
        out.push_str("#endif\n");
        out.push_str("}\n\n");

        // process_exit(code)
        out.push_str("static void bl_process_exit(int64_t code) {\n");
        out.push_str("    exit((int)code);\n");
        out.push_str("}\n\n");

        // time_now() -> int  (Unix epoch seconds)
        out.push_str("static int64_t bl_time_now(void) {\n");
        out.push_str("    return (int64_t)time(NULL);\n");
        out.push_str("}\n\n");

        // time_sleep(ms)
        out.push_str("static void bl_time_sleep(int64_t ms) {\n");
        out.push_str("#ifdef _WIN32\n");
        out.push_str("    Sleep((DWORD)(ms < 0 ? 0 : ms));\n");
        out.push_str("#else\n");
        out.push_str("    if (ms > 0) usleep((useconds_t)(ms * 1000));\n");
        out.push_str("#endif\n");
        out.push_str("}\n\n");

        // str_to_int(s) -> int
        out.push_str("static int64_t bl_str_to_int(const char* s) {\n");
        out.push_str("    if (!s) return 0;\n");
        out.push_str("    return (int64_t)strtoll(s, NULL, 10);\n");
        out.push_str("}\n\n");

        // str_to_float(s) -> double
        out.push_str("static double bl_str_to_float(const char* s) {\n");
        out.push_str("    if (!s) return 0.0;\n");
        out.push_str("    return strtod(s, NULL);\n");
        out.push_str("}\n\n");

        // str_contains(haystack, needle) -> bool
        out.push_str("static bool bl_str_contains(const char* h, const char* n) {\n");
        out.push_str("    if (!h || !n) return false;\n");
        out.push_str("    return strstr(h, n) != NULL;\n");
        out.push_str("}\n\n");

        // str_starts_with(s, prefix) -> bool
        out.push_str("static bool bl_str_starts_with(const char* s, const char* p) {\n");
        out.push_str("    if (!s || !p) return false;\n");
        out.push_str("    size_t pl = strlen(p);\n");
        out.push_str("    return strncmp(s, p, pl) == 0;\n");
        out.push_str("}\n\n");

        // str_ends_with(s, suffix) -> bool
        out.push_str("static bool bl_str_ends_with(const char* s, const char* suf) {\n");
        out.push_str("    if (!s || !suf) return false;\n");
        out.push_str("    size_t sl = strlen(s), sufl = strlen(suf);\n");
        out.push_str("    return sl >= sufl && strcmp(s + sl - sufl, suf) == 0;\n");
        out.push_str("}\n\n");

        // math_sqrt(x) -> double
        out.push_str("static double bl_math_sqrt(double x) { return sqrt(x); }\n\n");

        // math_floor(x) -> double
        out.push_str("static double bl_math_floor(double x) { return floor(x); }\n\n");

        // math_ceil(x) -> double
        out.push_str("static double bl_math_ceil(double x) { return ceil(x); }\n\n");

        // math_round(x) -> double
        out.push_str("static double bl_math_round(double x) { return round(x); }\n\n");

        // 2D Graphics Library Runtime
        out.push_str("/* ========================================================================= */\n");
        out.push_str("/* 2D Graphics Library Runtime (Win32 Double Buffered / Platform Fallback)  */\n");
        out.push_str("/* ========================================================================= */\n\n");
        out.push_str("#ifdef _WIN32\n");
        out.push_str("static HWND bl_hwnd = NULL;\n");
        out.push_str("static HDC bl_hdc = NULL;\n");
        out.push_str("static HDC bl_memdc = NULL;\n");
        out.push_str("static HBITMAP bl_bitmap = NULL;\n");
        out.push_str("static int bl_win_width = 800;\n");
        out.push_str("static int bl_win_height = 600;\n");
        out.push_str("static bool bl_should_close = false;\n\n");

        out.push_str("static LRESULT CALLBACK bl_wndproc(HWND hwnd, UINT msg, WPARAM wParam, LPARAM lParam) {\n");
        out.push_str("    if (msg == WM_CLOSE || msg == WM_DESTROY) {\n");
        out.push_str("        bl_should_close = true;\n");
        out.push_str("        return 0;\n");
        out.push_str("    }\n");
        out.push_str("    return DefWindowProcA(hwnd, msg, wParam, lParam);\n");
        out.push_str("}\n\n");

        out.push_str("static bool window_open(const char* title, int64_t w, int64_t h) {\n");
        out.push_str("    bl_win_width = (int)w;\n");
        out.push_str("    bl_win_height = (int)h;\n");
        out.push_str("    bl_should_close = false;\n");
        out.push_str("    HINSTANCE hInst = GetModuleHandleA(NULL);\n");
        out.push_str("    WNDCLASSEXA wc = {0};\n");
        out.push_str("    wc.cbSize = sizeof(WNDCLASSEXA);\n");
        out.push_str("    wc.style = CS_HREDRAW | CS_VREDRAW;\n");
        out.push_str("    wc.lpfnWndProc = bl_wndproc;\n");
        out.push_str("    wc.hInstance = hInst;\n");
        out.push_str("    wc.hCursor = LoadCursor(NULL, IDC_ARROW);\n");
        out.push_str("    wc.hbrBackground = (HBRUSH)(COLOR_WINDOW + 1);\n");
        out.push_str("    wc.lpszClassName = \"BlueprintWindowClass\";\n");
        out.push_str("    RegisterClassExA(&wc);\n");
        out.push_str("    RECT rc = {0, 0, bl_win_width, bl_win_height};\n");
        out.push_str("    AdjustWindowRect(&rc, WS_OVERLAPPEDWINDOW, FALSE);\n");
        out.push_str("    int total_w = rc.right - rc.left;\n");
        out.push_str("    int total_h = rc.bottom - rc.top;\n");
        out.push_str("    bl_hwnd = CreateWindowExA(0, \"BlueprintWindowClass\", title, WS_OVERLAPPEDWINDOW | WS_VISIBLE,\n");
        out.push_str("        CW_USEDEFAULT, CW_USEDEFAULT, total_w, total_h, NULL, NULL, hInst, NULL);\n");
        out.push_str("    if (!bl_hwnd) return false;\n");
        out.push_str("    bl_hdc = GetDC(bl_hwnd);\n");
        out.push_str("    bl_memdc = CreateCompatibleDC(bl_hdc);\n");
        out.push_str("    bl_bitmap = CreateCompatibleBitmap(bl_hdc, bl_win_width, bl_win_height);\n");
        out.push_str("    SelectObject(bl_memdc, bl_bitmap);\n");
        out.push_str("    ShowWindow(bl_hwnd, SW_SHOW);\n");
        out.push_str("    UpdateWindow(bl_hwnd);\n");
        out.push_str("    return true;\n");
        out.push_str("}\n\n");

        out.push_str("static void window_close(void) {\n");
        out.push_str("    if (bl_bitmap) { DeleteObject(bl_bitmap); bl_bitmap = NULL; }\n");
        out.push_str("    if (bl_memdc) { DeleteDC(bl_memdc); bl_memdc = NULL; }\n");
        out.push_str("    if (bl_hdc && bl_hwnd) { ReleaseDC(bl_hwnd, bl_hdc); bl_hdc = NULL; }\n");
        out.push_str("    if (bl_hwnd) { DestroyWindow(bl_hwnd); bl_hwnd = NULL; }\n");
        out.push_str("}\n\n");

        out.push_str("static bool window_should_close(void) { return bl_should_close; }\n\n");

        out.push_str("static void window_poll(void) {\n");
        out.push_str("    MSG msg;\n");
        out.push_str("    while (PeekMessageA(&msg, NULL, 0, 0, PM_REMOVE)) {\n");
        out.push_str("        TranslateMessage(&msg);\n");
        out.push_str("        DispatchMessageA(&msg);\n");
        out.push_str("    }\n");
        out.push_str("}\n\n");

        out.push_str("static void draw_clear(int64_t r, int64_t g, int64_t b) {\n");
        out.push_str("    if (!bl_memdc) return;\n");
        out.push_str("    HBRUSH brush = CreateSolidBrush(RGB((int)r, (int)g, (int)b));\n");
        out.push_str("    RECT rc = {0, 0, bl_win_width, bl_win_height};\n");
        out.push_str("    FillRect(bl_memdc, &rc, brush);\n");
        out.push_str("    DeleteObject(brush);\n");
        out.push_str("}\n\n");

        out.push_str("static void draw_rect(int64_t x, int64_t y, int64_t w, int64_t h, int64_t r, int64_t g, int64_t b) {\n");
        out.push_str("    if (!bl_memdc) return;\n");
        out.push_str("    HBRUSH brush = CreateSolidBrush(RGB((int)r, (int)g, (int)b));\n");
        out.push_str("    RECT rc = {(LONG)x, (LONG)y, (LONG)(x + w), (LONG)(y + h)};\n");
        out.push_str("    FillRect(bl_memdc, &rc, brush);\n");
        out.push_str("    DeleteObject(brush);\n");
        out.push_str("}\n\n");

        out.push_str("static void draw_circle(int64_t cx, int64_t cy, int64_t radius, int64_t r, int64_t g, int64_t b) {\n");
        out.push_str("    if (!bl_memdc) return;\n");
        out.push_str("    HBRUSH brush = CreateSolidBrush(RGB((int)r, (int)g, (int)b));\n");
        out.push_str("    HPEN pen = CreatePen(PS_SOLID, 1, RGB((int)r, (int)g, (int)b));\n");
        out.push_str("    HGDIOBJ old_brush = SelectObject(bl_memdc, brush);\n");
        out.push_str("    HGDIOBJ old_pen = SelectObject(bl_memdc, pen);\n");
        out.push_str("    Ellipse(bl_memdc, (int)(cx - radius), (int)(cy - radius), (int)(cx + radius), (int)(cy + radius));\n");
        out.push_str("    SelectObject(bl_memdc, old_brush);\n");
        out.push_str("    SelectObject(bl_memdc, old_pen);\n");
        out.push_str("    DeleteObject(brush);\n");
        out.push_str("    DeleteObject(pen);\n");
        out.push_str("}\n\n");

        out.push_str("static void draw_line(int64_t x1, int64_t y1, int64_t x2, int64_t y2, int64_t r, int64_t g, int64_t b) {\n");
        out.push_str("    if (!bl_memdc) return;\n");
        out.push_str("    HPEN pen = CreatePen(PS_SOLID, 1, RGB((int)r, (int)g, (int)b));\n");
        out.push_str("    HGDIOBJ old_pen = SelectObject(bl_memdc, pen);\n");
        out.push_str("    MoveToEx(bl_memdc, (int)x1, (int)y1, NULL);\n");
        out.push_str("    LineTo(bl_memdc, (int)x2, (int)y2);\n");
        out.push_str("    SelectObject(bl_memdc, old_pen);\n");
        out.push_str("    DeleteObject(pen);\n");
        out.push_str("}\n\n");

        out.push_str("static void draw_text(const char* text, int64_t x, int64_t y, int64_t size, int64_t r, int64_t g, int64_t b) {\n");
        out.push_str("    if (!bl_memdc || !text) return;\n");
        out.push_str("    HFONT font = CreateFontA((int)size, 0, 0, 0, FW_NORMAL, FALSE, FALSE, FALSE, ANSI_CHARSET,\n");
        out.push_str("        OUT_DEFAULT_PRECIS, CLIP_DEFAULT_PRECIS, DEFAULT_QUALITY, DEFAULT_PITCH | FF_DONTCARE, \"Arial\");\n");
        out.push_str("    HGDIOBJ old_font = SelectObject(bl_memdc, font);\n");
        out.push_str("    SetTextColor(bl_memdc, RGB((int)r, (int)g, (int)b));\n");
        out.push_str("    SetBkMode(bl_memdc, TRANSPARENT);\n");
        out.push_str("    TextOutA(bl_memdc, (int)x, (int)y, text, (int)strlen(text));\n");
        out.push_str("    SelectObject(bl_memdc, old_font);\n");
        out.push_str("    DeleteObject(font);\n");
        out.push_str("}\n\n");

        out.push_str("static void window_present(void) {\n");
        out.push_str("    if (!bl_hdc || !bl_memdc) return;\n");
        out.push_str("    BitBlt(bl_hdc, 0, 0, bl_win_width, bl_win_height, bl_memdc, 0, 0, SRCCOPY);\n");
        out.push_str("    Sleep(16);\n");
        out.push_str("}\n\n");

        out.push_str("static bool is_key_down(int64_t key) {\n");
        out.push_str("    return (GetAsyncKeyState((int)key) & 0x8000) != 0;\n");
        out.push_str("}\n");
        out.push_str("#else\n");
        out.push_str("static bool window_open(const char* title, int64_t w, int64_t h) { (void)title; (void)w; (void)h; return true; }\n");
        out.push_str("static void window_close(void) {}\n");
        out.push_str("static bool window_should_close(void) { return true; }\n");
        out.push_str("static void window_poll(void) {}\n");
        out.push_str("static void draw_clear(int64_t r, int64_t g, int64_t b) { (void)r; (void)g; (void)b; }\n");
        out.push_str("static void draw_rect(int64_t x, int64_t y, int64_t w, int64_t h, int64_t r, int64_t g, int64_t b) { (void)x; (void)y; (void)w; (void)h; (void)r; (void)g; (void)b; }\n");
        out.push_str("static void draw_circle(int64_t cx, int64_t cy, int64_t radius, int64_t r, int64_t g, int64_t b) { (void)cx; (void)cy; (void)radius; (void)r; (void)g; (void)b; }\n");
        out.push_str("static void draw_line(int64_t x1, int64_t y1, int64_t x2, int64_t y2, int64_t r, int64_t g, int64_t b) { (void)x1; (void)y1; (void)x2; (void)y2; (void)r; (void)g; (void)b; }\n");
        out.push_str("static void draw_text(const char* text, int64_t x, int64_t y, int64_t size, int64_t r, int64_t g, int64_t b) { (void)text; (void)x; (void)y; (void)size; (void)r; (void)g; (void)b; }\n");
        out.push_str("static void window_present(void) {}\n");
        out.push_str("static bool is_key_down(int64_t key) { (void)key; return false; }\n");
        out.push_str("#endif\n\n");

        // 1. Forward declare struct types
        for item in &program.items {
            if let Item::Struct(st) = item {
                out.push_str(&format!("typedef struct {} {};\n", st.name, st.name));
            }
        }
        out.push('\n');

        // 2. Define struct bodies
        for item in &program.items {
            if let Item::Struct(st) = item {
                out.push_str(&format!("struct {} {{\n", st.name));
                for f in &st.fields {
                    let c_type = Self::c_type(&f.ty);
                    out.push_str(&format!("    {} {};\n", c_type, f.name));
                }
                out.push_str("};\n\n");
            }
        }

        // 3. Forward declare function signatures
        for item in &program.items {
            if let Item::Func(func) = item {
                let ret_ty = func.return_ty.as_ref().map(Self::c_type).unwrap_or_else(|| "void".to_string());
                let params = Self::c_params(&func.params);
                out.push_str(&format!("{} {}({});\n", ret_ty, func.name, params));
            }
        }
        out.push('\n');

        // 4. Implement functions
        for item in &program.items {
            if let Item::Func(func) = item {
                let ret_ty = func.return_ty.as_ref().map(Self::c_type).unwrap_or_else(|| "void".to_string());
                let params = Self::c_params(&func.params);
                out.push_str(&format!("{} {}({}) {{\n", ret_ty, func.name, params));
                for stmt in &func.body {
                    Self::emit_stmt(&mut out, stmt, program, 1);
                }
                out.push_str("}\n\n");
            }
        }

        // 5. Entry point main() calling Blueprint Main()
        out.push_str("int main(int argc, char** argv) {\n");
        out.push_str("    (void)argc;\n");
        out.push_str("    (void)argv;\n");
        out.push_str("    Main();\n");
        out.push_str("#ifdef _WIN32\n");
        out.push_str("    if (bl_hwnd && !bl_should_close) {\n");
        out.push_str("        while (!window_should_close()) {\n");
        out.push_str("            window_poll();\n");
        out.push_str("            window_present();\n");
        out.push_str("        }\n");
        out.push_str("        window_close();\n");
        out.push_str("    }\n");
        out.push_str("#endif\n");
        out.push_str("    return 0;\n");
        out.push_str("}\n");

        out
    }

    fn c_type(ty: &Type) -> String {
        match ty {
            Type::Int => "int64_t".to_string(),
            Type::I8 => "int8_t".to_string(),
            Type::I16 => "int16_t".to_string(),
            Type::I32 => "int32_t".to_string(),
            Type::I64 => "int64_t".to_string(),
            Type::U8 => "uint8_t".to_string(),
            Type::U16 => "uint16_t".to_string(),
            Type::U32 => "uint32_t".to_string(),
            Type::U64 => "uint64_t".to_string(),
            Type::F32 => "float".to_string(),
            Type::F64 => "double".to_string(),
            Type::Bool => "bool".to_string(),
            Type::String => "const char*".to_string(),
            Type::Void => "void".to_string(),
            Type::Custom(name) => name.clone(),
        }
    }

    fn infer_c_type(expr: &Expr, program: &Program) -> String {
        match expr {
            Expr::Int(_) => "int64_t".to_string(),
            Expr::Float(_) => "double".to_string(),
            Expr::Bool(_) => "bool".to_string(),
            Expr::String(_) => "const char*".to_string(),
            Expr::StructInit(name, _) => name.clone(),
            Expr::BinaryOp(_, BinOp::Add, _) => "const char*".to_string(),
            Expr::BinaryOp(_, BinOp::Gt | BinOp::Lt | BinOp::Gte | BinOp::Lte | BinOp::EqEq | BinOp::Neq | BinOp::And | BinOp::Or, _) => "bool".to_string(),
            Expr::BinaryOp(l, _, r) => {
                if Self::is_float_expr(&l.expr) || Self::is_float_expr(&r.expr) {
                    "double".to_string()
                } else {
                    "int64_t".to_string()
                }
            }
            Expr::UnaryOp(UnOp::Not, _) => "bool".to_string(),
            Expr::UnaryOp(UnOp::Neg, inner) => {
                if Self::is_float_expr(&inner.expr) {
                    "double".to_string()
                } else {
                    "int64_t".to_string()
                }
            }
            Expr::Call(name, _) => {
                if name == "str_len" {
                    return "int64_t".to_string();
                }
                if name.starts_with("math_sqrt") || name.starts_with("math_floor")
                    || name.starts_with("math_ceil") || name.starts_with("math_round")
                    || name == "str_to_float"
                {
                    return "double".to_string();
                }
                if name.starts_with("math_") {
                    return "int64_t".to_string();
                }
                if name == "window_open" || name == "window_should_close" || name == "is_key_down"
                    || name == "file_write" || name == "file_exists" || name == "env_set"
                    || name == "str_contains" || name == "str_starts_with" || name == "str_ends_with"
                {
                    return "bool".to_string();
                }
                if name == "input" || name == "file_read" || name == "path_join"
                    || name == "path_ext" || name == "path_filename"
                    || name == "env_get" || name == "str_len"
                {
                    return "const char*".to_string();
                }
                if name == "time_now" || name == "str_to_int" {
                    return "int64_t".to_string();
                }
                // Look up in Blueprint functions
                for item in &program.items {
                    if let Item::Func(f) = item {
                        if &f.name == name {
                            if let Some(ref ty) = f.return_ty {
                                return Self::c_type(ty);
                            }
                        }
                    }
                }
                // Look up in C extern declarations — parse return type from signature
                for ext in &program.c_externs {
                    let sig = ext.signature.trim();
                    if let Some(paren_pos) = sig.find('(') {
                        let before = sig[..paren_pos].trim();
                        if let Some(func_name) = before.split_whitespace().last() {
                            if func_name == name {
                                // Return type is everything before the function name
                                let ret_part = before[..before.rfind(func_name).unwrap_or(0)].trim();
                                return match ret_part {
                                    "double" => "double".to_string(),
                                    "float" => "float".to_string(),
                                    "int" | "int32_t" => "int32_t".to_string(),
                                    "long" | "int64_t" => "int64_t".to_string(),
                                    "bool" => "bool".to_string(),
                                    "void" => "void".to_string(),
                                    _ => "const char*".to_string(),
                                };
                            }
                        }
                    }
                }
                "const char*".to_string()
            }
            Expr::MethodCall(_, method, _) => {
                for item in &program.items {
                    if let Item::Func(f) = item {
                        if &f.name == method {
                            if let Some(ref ty) = f.return_ty {
                                return Self::c_type(ty);
                            }
                        }
                    }
                }
                "const char*".to_string()
            }
            _ => "const char*".to_string(),
        }
    }

    fn is_float_expr(expr: &Expr) -> bool {
        match expr {
            Expr::Float(_) => true,
            Expr::BinaryOp(l, _, r) => Self::is_float_expr(&l.expr) || Self::is_float_expr(&r.expr),
            Expr::UnaryOp(_, operand) => Self::is_float_expr(&operand.expr),
            _ => false,
        }
    }

    fn c_params(params: &[Param]) -> String {
        if params.is_empty() {
            return "void".to_string();
        }
        params
            .iter()
            .map(|p| {
                let ty = p.ty.as_ref().map(Self::c_type).unwrap_or_else(|| "const char*".to_string());
                format!("{} {}", ty, p.name)
            })
            .collect::<Vec<_>>()
            .join(", ")
    }

    fn emit_stmt(out: &mut String, stmt: &Stmt, program: &Program, indent_level: usize) {
        let ind = "    ".repeat(indent_level);
        match stmt {
            Stmt::VarDef(v) => {
                let expr_code = Self::emit_expr(&v.expr.expr);
                let ty_str = if let Some(ref ty) = v.explicit_ty {
                    Self::c_type(ty)
                } else {
                    Self::infer_c_type(&v.expr.expr, program)
                };
                out.push_str(&format!("{}{} {} = {};\n", ind, ty_str, v.name, expr_code));
            }
            Stmt::Return(expr_opt, _) => {
                if let Some(e) = expr_opt {
                    out.push_str(&format!("{}return {};\n", ind, Self::emit_expr(&e.expr)));
                } else {
                    out.push_str(&format!("{}return;\n", ind));
                }
            }
            Stmt::If(if_stmt) => {
                let cond = Self::emit_expr(&if_stmt.condition.expr);
                out.push_str(&format!("{}if ({}) {{\n", ind, cond));
                for s in &if_stmt.then_branch {
                    Self::emit_stmt(out, s, program, indent_level + 1);
                }
                if let Some(ref else_branch) = if_stmt.else_branch {
                    out.push_str(&format!("{}}} else {{\n", ind));
                    for s in else_branch {
                        Self::emit_stmt(out, s, program, indent_level + 1);
                    }
                }
                out.push_str(&format!("{}}}\n", ind));
            }
            Stmt::Expr(e) => {
                let code = Self::emit_expr(&e.expr);
                out.push_str(&format!("{}{};\n", ind, code));
            }
        }
    }

    fn emit_expr(expr: &Expr) -> String {
        match expr {
            Expr::Int(n) => format!("{}LL", n),
            Expr::Float(f) => {
                if f.fract() == 0.0 {
                    format!("{:.1}", f)
                } else {
                    format!("{}", f)
                }
            }
            Expr::Bool(b) => if *b { "true".to_string() } else { "false".to_string() },
            Expr::String(s) => {
                let escaped = s.replace('\\', "\\\\").replace('"', "\\\"").replace('\n', "\\n");
                format!("\"{}\"", escaped)
            }
            Expr::Ident(name) => name.clone(),
            Expr::BinaryOp(left, op, right) => {
                let l = Self::emit_expr(&left.expr);
                let r = Self::emit_expr(&right.expr);
                match op {
                    BinOp::Add => {
                        // Check if string concatenation
                        format!("bl_concat(bl_to_str({}), bl_to_str({}))", l, r)
                    }
                    BinOp::Sub => format!("({} - {})", l, r),
                    BinOp::Mul => format!("({} * {})", l, r),
                    BinOp::Div => format!("({} / {})", l, r),
                    BinOp::Gt => format!("({} > {})", l, r),
                    BinOp::Lt => format!("({} < {})", l, r),
                    BinOp::Gte => format!("({} >= {})", l, r),
                    BinOp::Lte => format!("({} <= {})", l, r),
                    BinOp::EqEq => format!("({} == {})", l, r),
                    BinOp::Neq => format!("({} != {})", l, r),
                    BinOp::And => format!("({} && {})", l, r),
                    BinOp::Or => format!("({} || {})", l, r),
                }
            }
            Expr::UnaryOp(op, operand) => {
                let inner = Self::emit_expr(&operand.expr);
                match op {
                    UnOp::Neg => format!("(-{})", inner),
                    UnOp::Not => format!("(!{})", inner),
                }
            }
            Expr::Call(name, args) => {
                if name == "output" {
                    if let Some(first_arg) = args.first() {
                        let arg_code = Self::emit_expr(&first_arg.expr);
                        return format!("bl_output_str(bl_to_str({}))", arg_code);
                    }
                    return "bl_output_str(\"\")".to_string();
                }
                if name == "input" {
                    let prompt_code = if let Some(first_arg) = args.first() {
                        Self::emit_expr(&first_arg.expr)
                    } else {
                        "\"\"".to_string()
                    };
                    return format!("bl_input({})", prompt_code);
                }
                if name == "str_len" {
                    let s_code = if let Some(first_arg) = args.first() {
                        Self::emit_expr(&first_arg.expr)
                    } else {
                        "\"\"".to_string()
                    };
                    return format!("bl_str_len({})", s_code);
                }
                if name == "math_abs" {
                    let n = Self::emit_expr(&args[0].expr);
                    return format!("bl_math_abs({})", n);
                }
                if name == "math_pow" {
                    let b = Self::emit_expr(&args[0].expr);
                    let e = Self::emit_expr(&args[1].expr);
                    return format!("bl_math_pow({}, {})", b, e);
                }
                if name == "math_min" {
                    let a = Self::emit_expr(&args[0].expr);
                    let b = Self::emit_expr(&args[1].expr);
                    return format!("bl_math_min({}, {})", a, b);
                }
                if name == "math_max" {
                    let a = Self::emit_expr(&args[0].expr);
                    let b = Self::emit_expr(&args[1].expr);
                    return format!("bl_math_max({}, {})", a, b);
                }
                // Phase 4: Extended stdlib
                if name == "math_sqrt" {
                    return format!("bl_math_sqrt({})", Self::emit_expr(&args[0].expr));
                }
                if name == "math_floor" {
                    return format!("bl_math_floor({})", Self::emit_expr(&args[0].expr));
                }
                if name == "math_ceil" {
                    return format!("bl_math_ceil({})", Self::emit_expr(&args[0].expr));
                }
                if name == "math_round" {
                    return format!("bl_math_round({})", Self::emit_expr(&args[0].expr));
                }
                if name == "file_read" {
                    return format!("bl_file_read({})", Self::emit_expr(&args[0].expr));
                }
                if name == "file_write" {
                    return format!("bl_file_write({}, {})", Self::emit_expr(&args[0].expr), Self::emit_expr(&args[1].expr));
                }
                if name == "file_exists" {
                    return format!("bl_file_exists({})", Self::emit_expr(&args[0].expr));
                }
                if name == "path_join" {
                    return format!("bl_path_join({}, {})", Self::emit_expr(&args[0].expr), Self::emit_expr(&args[1].expr));
                }
                if name == "path_ext" {
                    return format!("bl_path_ext({})", Self::emit_expr(&args[0].expr));
                }
                if name == "path_filename" {
                    return format!("bl_path_filename({})", Self::emit_expr(&args[0].expr));
                }
                if name == "env_get" {
                    return format!("bl_env_get({})", Self::emit_expr(&args[0].expr));
                }
                if name == "env_set" {
                    return format!("bl_env_set({}, {})", Self::emit_expr(&args[0].expr), Self::emit_expr(&args[1].expr));
                }
                if name == "process_exit" {
                    return format!("bl_process_exit({})", Self::emit_expr(&args[0].expr));
                }
                if name == "time_now" {
                    return "bl_time_now()".to_string();
                }
                if name == "time_sleep" {
                    return format!("bl_time_sleep({})", Self::emit_expr(&args[0].expr));
                }
                if name == "str_to_int" {
                    return format!("bl_str_to_int({})", Self::emit_expr(&args[0].expr));
                }
                if name == "str_to_float" {
                    return format!("bl_str_to_float({})", Self::emit_expr(&args[0].expr));
                }
                if name == "str_contains" {
                    return format!("bl_str_contains({}, {})", Self::emit_expr(&args[0].expr), Self::emit_expr(&args[1].expr));
                }
                if name == "str_starts_with" {
                    return format!("bl_str_starts_with({}, {})", Self::emit_expr(&args[0].expr), Self::emit_expr(&args[1].expr));
                }
                if name == "str_ends_with" {
                    return format!("bl_str_ends_with({}, {})", Self::emit_expr(&args[0].expr), Self::emit_expr(&args[1].expr));
                }
                let rendered_args = args.iter().map(|a| Self::emit_expr(&a.expr)).collect::<Vec<_>>().join(", ");
                format!("{}({})", name, rendered_args)
            }
            Expr::FieldAccess(target, field) => {
                let t = Self::emit_expr(&target.expr);
                format!("{}.{}", t, field)
            }
            Expr::StructInit(struct_name, fields) => {
                let rendered_fields = fields
                    .iter()
                    .map(|(fname, val)| {
                        if fname.starts_with('_') {
                            Self::emit_expr(&val.expr)
                        } else {
                            format!(".{} = {}", fname, Self::emit_expr(&val.expr))
                        }
                    })
                    .collect::<Vec<_>>()
                    .join(", ");
                format!("({}){{ {} }}", struct_name, rendered_fields)
            }
            Expr::MethodCall(target, method, args) => {
                let rendered_args = args.iter().map(|a| Self::emit_expr(&a.expr)).collect::<Vec<_>>().join(", ");
                // If calling a function on an imported module (e.g. library.example_func(...))
                if let Expr::Ident(_mod_name) = &target.expr {
                    // Call the function directly
                    return format!("{}({})", method, rendered_args);
                }
                let t = Self::emit_expr(&target.expr);
                if rendered_args.is_empty() {
                    format!("{}_{}({})", t, method, t)
                } else {
                    format!("{}_{}({}, {})", t, method, t, rendered_args)
                }
            }
        }
    }

    /// Compiles directly to a standalone native binary using the system C compiler (gcc/clang).
    /// Does NOT invoke Cargo, does NOT embed the Blueprint interpreter.
    pub fn compile_to_executable(
        program: &Program,
        _source: &str,
        output_exe: &Path,
    ) -> Result<PathBuf, CompileError> {
        use std::sync::atomic::{AtomicUsize, Ordering};
        static BUILD_ID: AtomicUsize = AtomicUsize::new(0);
        let id = BUILD_ID.fetch_add(1, Ordering::SeqCst);
        let temp_dir = std::env::temp_dir().join(format!("bl_build_{}_{}", std::process::id(), id));
        let _ = fs::create_dir_all(&temp_dir);

        let c_source = Self::emit_c(program);
        let c_file = temp_dir.join("app.c");
        fs::write(&c_file, c_source).map_err(|e| {
            CompileError::new(&format!("Failed to write generated C file: {}", e))
        })?;

        if let Some(parent) = output_exe.parent() {
            let _ = fs::create_dir_all(parent);
        }

        // Determine output path — on Linux strip .exe if present, add nothing
        let final_output = if cfg!(target_os = "windows") {
            // Windows: keep as-is (caller may pass .exe already)
            output_exe.to_path_buf()
        } else {
            // Linux/macOS: strip .exe extension if present
            if output_exe.extension().map_or(false, |e| e == "exe") {
                output_exe.with_extension("")
            } else {
                output_exe.to_path_buf()
            }
        };

        // Collect extra linker libraries declared via C.Link(...)
        let mut extra_libs: Vec<String> = Vec::new();
        for cl in &program.c_links {
            extra_libs.push(cl.lib.clone());
        }

        // Prefer gcc, fall back to cc
        let compiler = if cfg!(target_os = "windows") { "gcc" } else { "cc" };
        let mut cmd = Command::new(compiler);
        cmd.arg("-O2")
            .arg("-std=c11")
            .arg("-o")
            .arg(&final_output)
            .arg(&c_file);

        if cfg!(target_os = "windows") {
            cmd.arg("-lgdi32").arg("-luser32").arg("-lm");
        } else {
            cmd.arg("-lm").arg("-lpthread");
        }

        for lib in &extra_libs {
            cmd.arg(format!("-l{}", lib));
        }

        let output = cmd.output().map_err(|e| {
            CompileError::new(&format!(
                "Failed to invoke native compiler '{}'. Make sure GCC/Clang is installed: {}",
                compiler, e
            ))
        })?;

        let _ = fs::remove_dir_all(&temp_dir);

        if !output.status.success() {
            let stderr = String::from_utf8_lossy(&output.stderr);
            return Err(CompileError::new(&format!(
                "Native compiler ({}) reported build errors:\n{}",
                compiler, stderr
            )));
        }

        if !final_output.exists() {
            return Err(CompileError::new("Executable binary was not produced"));
        }

        Ok(final_output)
    }
}
